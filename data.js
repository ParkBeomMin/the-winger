/* 받침에 맞는 조사 — josa("마테오", "이/가") → "마테오가" */
function josa(w, pair) {
  const c = String(w).charCodeAt(String(w).length - 1);
  const has = c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0;
  const [a, b] = pair.split("/");
  return w + (has ? a : b);
}

